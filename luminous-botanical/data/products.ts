function seedTerpenes(id: string): { name: string; pct: number }[] {
  let h = 0;
  for (let i = 0; i < id.length; i++) h = (h * 31 + id.charCodeAt(i)) >>> 0;
  const picks = TERP_SEED.slice().sort((a, b) => ((h >> a.name.length) % 7) - ((h >> b.name.length) % 7)).slice(0, 3);
  return picks.map((t, i) => {
    const span = t.hi - t.lo;
    const pct = Math.round((t.lo + ((h >> (i * 3)) % 100) / 100 * span) * 10) / 10;
    return { name: t.name, pct };
  });
}

function seedEffects(id: string, strain: string): { label: string; value: number }[] {
  let h = 0;
  for (let i = 0; i < id.length; i++) h = (h * 31 + id.charCodeAt(i)) >>> 0;
  const pairs: Record<string, [string, string]> = {
    Indica: ['Relax', 'Body'],
    Sativa: ['Euphoria', 'Focus'],
    Hybrid: ['Balance', 'Mood'],
    CBD: ['Calm', 'Clarity'],
    'N/A': ['Ease', 'Lift'],
  };
  const [a, b] = pairs[strain] ?? pairs['N/A'];
  return [
    { label: a, value: 45 + (h % 50) },
    { label: b, value: 35 + ((h >> 4) % 55) },
  ];
}

